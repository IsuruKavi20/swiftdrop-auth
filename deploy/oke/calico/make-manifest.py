"""Builds deploy/oke/calico/calico-policy-only.yaml from the official Calico manifest, with Oracle's edits for
OKE with VCN-native pod networking (docs: "Example: Installing Calico and Setting Up Network Policies").

Calico runs here in "policy-only" mode: it does NOT replace the network (Oracle's VCN-native CNI keeps doing that),
it only enforces Kubernetes NetworkPolicies with the node's firewall (iptables/nftables).

    curl -sSfL https://raw.githubusercontent.com/projectcalico/calico/v3.32.0/manifests/calico-policy-only.yaml -o upstream.yaml
    python deploy/oke/calico/make-manifest.py upstream.yaml deploy/oke/calico/calico-policy-only.yaml
"""
import sys

import yaml

CNI_VOLUMES = {"cni-bin-dir", "cni-net-dir", "cni-log-dir"}
ORACLE_ENV = [
    {"name": "FELIX_INTERFACEPREFIX", "value": "oci"},          # pod interfaces on OKE are named oci*
    {"name": "NO_DEFAULT_POOLS", "value": "true"},              # Calico doesn't hand out pod IPs here
    {"name": "FELIX_CHAININSERTMODE", "value": "Append"},       # after Oracle's own firewall rules
    {"name": "FELIX_IPTABLESMANGLEALLOWACTION", "value": "Return"},
    {"name": "FELIX_IPTABLESBACKEND", "value": "NFT"},          # Oracle Linux 8 nodes use nftables
]


def patch_calico_node(daemonset):
    pod = daemonset["spec"]["template"]["spec"]
    pod.pop("initContainers", None)  # CNI installers: not needed, Oracle's CNI stays in charge
    pod["volumes"] = [v for v in pod.get("volumes", []) if v["name"] not in CNI_VOLUMES]
    container = next(c for c in pod["containers"] if c["name"] == "calico-node")
    container.pop("envFrom", None)
    container["env"] = [e for e in container.get("env", []) if e["name"] != "FELIX_TYPHAK8SSERVICENAME"]
    container["env"] += ORACLE_ENV
    container["volumeMounts"] = [m for m in container.get("volumeMounts", []) if m["name"] not in CNI_VOLUMES]


def main(source, target):
    with open(source, encoding="utf-8") as f:
        documents = [d for d in yaml.safe_load_all(f) if d]
    patched = 0
    for doc in documents:
        if doc.get("kind") == "DaemonSet" and doc["metadata"]["name"] == "calico-node":
            patch_calico_node(doc)
            patched += 1
    if patched != 1:
        sys.exit(f"expected exactly one calico-node DaemonSet, found {patched}")
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write("# GENERATED by deploy/oke/calico/make-manifest.py from Calico v3.32.0 calico-policy-only.yaml.\n")
        f.write("# Do not edit by hand: change the script and regenerate. Apply: kubectl apply -f <this file>\n")
        yaml.safe_dump_all(documents, f, sort_keys=False, explicit_start=True)
    print(f"wrote {target} ({len(documents)} objects)")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
