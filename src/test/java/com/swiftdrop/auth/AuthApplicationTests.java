package com.swiftdrop.auth;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.context.ApplicationContext;
import org.springframework.context.annotation.Import;
import org.springframework.security.core.userdetails.UserDetailsService;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.test.context.ActiveProfiles;

import static org.assertj.core.api.Assertions.assertThat;

@Import(TestcontainersConfiguration.class)
@SpringBootTest
@ActiveProfiles("test")
class AuthApplicationTests {

	@Autowired
	private ApplicationContext context;

	@Autowired
	private PasswordEncoder passwordEncoder;

	@Test
	void noAutoGeneratedInMemoryUserExists() {
		assertThat(context.getBeanNamesForType(UserDetailsService.class)).isEmpty();
	}

	@Test
	void passwordEncoderUsesConfiguredArgon2WithAlgorithmPrefix() {
		assertThat(passwordEncoder.encode("a long test passphrase"))
				.startsWith("{argon2}$argon2id$")
				.contains("m=19456,t=2,p=1");
	}

}
